#!/usr/bin/env python3
"""Generates names.h: the species names in the languages that have their own.

  python3 tools/gen_names.py           # write names.h
  python3 tools/gen_names.py --check   # fail if names.h is not what this emits

Only German and French get a table. Spanish, Italian and Portuguese use the
English names in the official games (PokeAPI has a handful of spelling
variants for ES/IT and no Portuguese at all), so they fall back to DEX_TBL.

The source is PokeAPI's own data repository, pinned to one commit so a re-run
cannot change a name under a player's feet: pokemon_species_names.csv carries
every species in every language. Fetched with curl, not urllib -- this Python
has no certificate store on some machines (see check_sprites.py).

What the panel can draw decides the spelling:
  - upper case, like the English table;
  - German keeps AE/OE/UE as real umlauts, which i18n.cpp maps onto the font's
    own glyphs (GLCD_MAP) -- the same mechanism as the UI strings. ss has no
    capital glyph and upper-cases to SS, as German does anyway;
  - every other accent is dropped, French included: the French UI is
    unaccented and code page 437 lacks most accented capitals.
NIDORAN (29/32) is left to DEX_TBL: its female/male signs have no glyph, and
the English table spells them NIDORAN H / NIDORAN M.
"""
import os
import subprocess
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from dex_data import DEX

POKEAPI_COMMIT = '2bf639e5572812a67d2b94903fdcb9d095f5aeb2'
URL = ('https://raw.githubusercontent.com/PokeAPI/pokeapi/%s/data/v2/csv/'
       'pokemon_species_names.csv' % POKEAPI_COMMIT)
CACHE = os.path.join(HERE, 'downloads', 'pokemon_species_names_%s.csv' % POKEAPI_COMMIT[:12])
OUT = os.path.join(ROOT, 'names.h')

# PokeAPI's local_language_id for the languages that get a table, and the
# characters each may keep beyond ASCII (they must be in GLCD_MAP, i18n.cpp)
LANGS = [('DE', 6, set('ÄÖÜ')), ('FR', 5, set())]
SKIP = {29, 32}            # NIDORAN: see above
MAX_LEN = 12               # the longest English name; the layout is sized for it


def fetch():
    if not os.path.exists(CACHE):
        os.makedirs(os.path.dirname(CACHE), exist_ok=True)
        tmp = CACHE + '.part'
        r = subprocess.run(['curl', '-sfL', '-o', tmp, URL])
        if r.returncode != 0:
            sys.exit('could not download %s (curl exit %d)' % (URL, r.returncode))
        os.replace(tmp, CACHE)
    import csv
    names = {}
    with open(CACHE, encoding='utf-8') as f:
        for row in csv.DictReader(f):
            names[(int(row['pokemon_species_id']), int(row['local_language_id']))] = row['name']
    return names


def panel_spelling(name, keep):
    up = name.upper()                       # also turns a German ss into SS
    out = []
    for c in up:
        if ord(c) < 128 or c in keep:
            out.append(c)
            continue
        base = unicodedata.normalize('NFKD', c)
        base = ''.join(b for b in base if not unicodedata.combining(b))
        if not base or any(ord(b) >= 128 for b in base):
            raise ValueError('no spelling for %r in %r' % (c, name))
        out.append(base)
    return ''.join(out)


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def emit():
    names = fetch()
    count = max(d[0] for d in DEX)
    english = {d[0]: d[2] for d in DEX}
    lines = [
        '#pragma once',
        '// GENERATED by tools/gen_names.py from PokeAPI\'s pokemon_species_names.csv',
        '// (commit %s) - do not edit.' % POKEAPI_COMMIT[:12],
        '//',
        '// Species names in the languages whose games use their own. nullptr means',
        '// "same as English": speciesName() in i18n.cpp falls back to DEX_TBL. UTF-8;',
        '// i18n.cpp maps the umlauts onto the panel font\'s glyphs.',
        '#include "dex.h"',
        '',
    ]
    for code, lang_id, keep in LANGS:
        lines.append('static const char *const SPECIES_NAME_%s[DEX_COUNT + 1] = {' % code)
        lines.append('  nullptr,')
        differ = 0
        for n in range(1, count + 1):
            src = names.get((n, lang_id))
            if src is None:
                sys.exit('%s has no name for #%d' % (code, n))
            spelled = None if n in SKIP else panel_spelling(src, keep)
            if spelled is not None and len(spelled) > MAX_LEN:
                sys.exit('%s #%d %r is longer than %d' % (code, n, spelled, MAX_LEN))
            if spelled is None or spelled == english[n]:
                lines.append('  nullptr,  // %d %s' % (n, english[n]))
            else:
                differ += 1
                lines.append('  %s,  // %d %s' % (c_string(spelled), n, english[n]))
        lines.append('};')
        lines.append('// %s: %d of %d differ from English' % (code, differ, count))
        lines.append('')
    return '\n'.join(lines)


def main():
    text = emit()
    if '--check' in sys.argv:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if have != text:
            sys.exit('names.h is stale: run python3 tools/gen_names.py')
        print('names.h is current')
        return
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
